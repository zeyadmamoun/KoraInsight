package com.zeyadmamoun.matchdetails.ui

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.zeyadmamoun.core.common.result.NetworkStatus
import com.zeyadmamoun.core.common.result.Result
import com.zeyadmamoun.data.model.standings.LeagueStandings
import com.zeyadmamoun.data.model.summary.MatchDetails
import com.zeyadmamoun.data.repository.LeaguesRepository
import com.zeyadmamoun.data.repository.MatchDetailsRepository
import dagger.assisted.Assisted
import dagger.assisted.AssistedFactory
import dagger.assisted.AssistedInject
import dagger.hilt.android.lifecycle.HiltViewModel
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

/**
 * UI state representation for the Match Details screen.
 *
 * @property networkStatus Current loading, success, or error status.
 * @property matchDetails Domain match data including score, lineups, stats, and timeline.
 * @property isRefreshing Whether a user pull-to-refresh action is currently in flight.
 * @property standingsStatus Loading, success, or error status for the standings table.
 * @property leagueStandings Current league standings table for the match's league.
 */
data class MatchDetailsUiState(
    val networkStatus: NetworkStatus = NetworkStatus.Loading,
    val matchDetails: MatchDetails? = null,
    val isRefreshing: Boolean = false,
    val standingsStatus: NetworkStatus = NetworkStatus.Loading,
    val leagueStandings: LeagueStandings? = null
)

/**
 * ViewModel responsible for fetching and maintaining match detail state and league standings.
 *
 * Uses Dagger/Hilt Assisted Injection ([AssistedInject] and [AssistedFactory]) to receive
 * runtime navigation arguments ([matchId] and [leagueSlug]) directly at instantiation.
 *
 * ### Architectural Decision: `init` vs `LaunchedEffect`
 * Initial data loading ([loadMatchDetails]) is deliberately triggered inside init() rather than
 * from a `LaunchedEffect` in the Composable layer:
 * - **Survives Configuration Changes**: The ViewModel is retained across screen rotations and theme
 *   toggles without re-triggering network requests or causing UI flickering.
 * - **Unidirectional Data Flow**: Decouples business logic from the UI lifecycle, keeping the Composable
 *   strictly passive (observing [uiState] via state flow).
 *
 * @param matchId Unique identifier of the match provided via navigation arguments.
 * @param leagueSlug Optional league slug identifier (e.g. "eng.1") for scoped ESPN endpoints.
 * @param matchDetailsRepository Repository providing live and cached match details.
 * @param leaguesRepository Repository providing league standings.
 */
@HiltViewModel(assistedFactory = MatchDetailsViewModel.Factory::class)
class MatchDetailsViewModel @AssistedInject constructor(
    @Assisted("matchId") private val matchId: String,
    @Assisted("leagueSlug") private val leagueSlug: String,
    private val matchDetailsRepository: MatchDetailsRepository,
    private val leaguesRepository: LeaguesRepository
) : ViewModel() {

    /**
     * Assisted factory generated by Hilt to inject [MatchDetailsViewModel] with runtime arguments.
     */
    @AssistedFactory
    interface Factory {
        fun create(
            @Assisted("matchId") matchId: String,
            @Assisted("leagueSlug") leagueSlug: String
        ): MatchDetailsViewModel
    }

    private val _uiState = MutableStateFlow(MatchDetailsUiState())
    val uiState: StateFlow<MatchDetailsUiState> = _uiState.asStateFlow()

    private var currentMatchId: String = ""
    private var currentLeagueSlug: String = ""

    init {
        currentMatchId = matchId
        currentLeagueSlug = leagueSlug

        if (matchId.isNotBlank()) {
            loadMatchDetails(matchId, leagueSlug)
        }
        if (leagueSlug.isNotBlank()) {
            loadStandings(leagueSlug)
        }
    }

    /**
     * Loads match details from [matchDetailsRepository].
     *
     * @param matchId The unique match ID.
     * @param leagueSlug The league slug identifier.
     * @param isForceRefresh Whether to bypass local cache and force a remote network fetch.
     */
    fun loadMatchDetails(
        matchId: String = "",
        leagueSlug: String = "",
        isForceRefresh: Boolean = false
    ) {
        val targetMatchId = matchId.ifBlank { currentMatchId }
        val targetLeagueSlug = leagueSlug.ifBlank { currentLeagueSlug }
        if (targetMatchId.isBlank()) return
        currentMatchId = targetMatchId
        currentLeagueSlug = targetLeagueSlug

        viewModelScope.launch {
            matchDetailsRepository.getMatchDetails(targetMatchId, targetLeagueSlug, isForceRefresh).collect { result ->
                when (result) {
                    is Result.Loading -> {
                        _uiState.update {
                            it.copy(networkStatus = NetworkStatus.Loading)
                        }
                    }

                    is Result.Success -> {
                        val details = result.data
                        _uiState.update {
                            it.copy(
                                networkStatus = NetworkStatus.Success,
                                matchDetails = details
                            )
                        }

                        // Preload standings if not already loaded or if leagueSlug was determined from match details
                        if (_uiState.value.leagueStandings == null) {
                            val effectiveSlug = currentLeagueSlug.ifBlank { details.leagueSlug }
                            if (effectiveSlug.isNotBlank()) {
                                currentLeagueSlug = effectiveSlug
                                loadStandings(effectiveSlug)
                            }
                        }
                    }

                    is Result.Error -> {
                        _uiState.update {
                            it.copy(
                                networkStatus = NetworkStatus.Error(
                                    result.message ?: "Failed to fetch match details"
                                )
                            )
                        }
                    }
                }
            }
        }
    }

    /**
     * Loads league standings for [leagueSlug] using [leaguesRepository].
     *
     * @param leagueSlug The league slug identifier (e.g. "eng.1").
     * @param isForceRefresh Whether to force a reload even if standings are already cached.
     */
    fun loadStandings(
        leagueSlug: String = currentLeagueSlug,
        isForceRefresh: Boolean = false
    ) {
        val slug = leagueSlug.ifBlank { currentLeagueSlug }
        if (slug.isBlank()) return
        if (!isForceRefresh && _uiState.value.leagueStandings != null) return

        currentLeagueSlug = slug

        viewModelScope.launch {
            leaguesRepository.getStandings(slug).collect { result ->
                when (result) {
                    is Result.Loading -> {
                        _uiState.update { it.copy(standingsStatus = NetworkStatus.Loading) }
                    }
                    is Result.Success -> {
                        _uiState.update {
                            it.copy(
                                standingsStatus = NetworkStatus.Success,
                                leagueStandings = result.data
                            )
                        }
                    }
                    is Result.Error -> {
                        _uiState.update {
                            it.copy(
                                standingsStatus = NetworkStatus.Error(
                                    result.message ?: "Failed to load standings"
                                )
                            )
                        }
                    }
                }
            }
        }
    }

    /**
     * Triggers a force refresh for the active match details and standings.
     */
    fun refresh() {
        if (currentMatchId.isNotBlank()) {
            loadMatchDetails(currentMatchId, currentLeagueSlug, isForceRefresh = true)
        }
        if (currentLeagueSlug.isNotBlank()) {
            loadStandings(currentLeagueSlug, isForceRefresh = true)
        }
    }
}
